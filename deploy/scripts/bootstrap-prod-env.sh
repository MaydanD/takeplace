#!/usr/bin/env bash
# =============================================================================
# Takeplace — generate the production `.env` for the closed test stand.
#
# Creates the file next to `docker-compose.prod.yml` (default: the repository
# root of the checkout on the server) with fresh random secrets.
#
#   sudo bash deploy/scripts/bootstrap-prod-env.sh \
#        --domain takeplace.94-16-106-2.sslip.io
#
# * refuses to overwrite an existing .env (use --force to rotate);
# * writes mode 600;
# * NEVER prints a secret value;
# * detects the Caddy container's address on the shared `edge` network, which is
#   the only trusted reverse proxy for TAKEPLACE_FORWARDED_ALLOW_IPS (§39.5).
#
# Requires: openssl, docker.
# =============================================================================
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"

env_path="$repo_root/.env"
domain=""
caddy_container="infra-caddy-1"
force=0

usage() {
  sed -n '2,19p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) domain="${2:?}"; shift 2 ;;
    --env) env_path="${2:?}"; shift 2 ;;
    --caddy-container) caddy_container="${2:?}"; shift 2 ;;
    --force) force=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "unknown argument: $1" >&2; usage 1 ;;
  esac
done

[[ -n "$domain" ]] || { echo "error: --domain is required" >&2; usage 1; }

if [[ -e "$env_path" && "$force" -ne 1 ]]; then
  echo "error: $env_path already exists; refusing to overwrite (use --force to rotate)" >&2
  exit 1
fi

command -v openssl >/dev/null 2>&1 || { echo "error: openssl is required" >&2; exit 1; }
command -v docker >/dev/null 2>&1 || { echo "error: docker is required" >&2; exit 1; }

# --- locate the trusted reverse proxy address --------------------------------
caddy_ip="$(docker inspect "$caddy_container" \
  --format '{{(index .NetworkSettings.Networks "edge").IPAddress}}' 2>/dev/null || true)"
if [[ -z "$caddy_ip" ]]; then
  echo "error: could not resolve $caddy_container on the 'edge' network." >&2
  echo "       Is the infra compose project running? See deploy/scripts/check-proxy-ip.sh" >&2
  exit 1
fi

# --- secrets (never echoed) ---------------------------------------------------
# 64 hex chars = 256 bits, comfortably above the 16-char production minimum.
gen_secret() { openssl rand -hex 32; }
gen_base64url_32() { openssl rand -base64 32 | tr '+/' '-_' | tr -d '='; }

app_password="$(gen_secret)"
migrator_password="$(gen_secret)"
idempotency_key="$(gen_secret)"
abuse_key="$(gen_secret)"
vk_key="$(gen_base64url_32)"

umask 077
cat > "$env_path" <<EOF
# =============================================================================
# Takeplace — production environment (generated by bootstrap-prod-env.sh).
#
# NEVER commit this file. Mode is 600 and it holds production secrets.
# Regenerate only via deploy/scripts/bootstrap-prod-env.sh --force.
# =============================================================================

# --- Deployment --------------------------------------------------------------
TAKEPLACE_ENV=production
TAKEPLACE_LOG_LEVEL=INFO
TAKEPLACE_IMAGE_TAG=local

# --- Database (isolated logical database in the shared PostgreSQL) -----------
TAKEPLACE_DB_HOST=postgres
TAKEPLACE_DB_PORT=5432
TAKEPLACE_DB_NAME=takeplace
TAKEPLACE_DB_APP_USER=takeplace_app
TAKEPLACE_DB_APP_PASSWORD=${app_password}
TAKEPLACE_DB_MIGRATOR_USER=takeplace_migrator
TAKEPLACE_DB_MIGRATOR_PASSWORD=${migrator_password}
# api => pool+overflow = 5 connections, worker => 3. The shared instance runs
# max_connections=30 and already serves two other applications.
TAKEPLACE_DB_POOL_SIZE=3
TAKEPLACE_DB_MAX_OVERFLOW=2
# Production baseline timeouts (PROJECT-SPEC §32.6), stated explicitly.
TAKEPLACE_DB_STATEMENT_TIMEOUT_MS=10000
TAKEPLACE_DB_LOCK_TIMEOUT_MS=3000
TAKEPLACE_DB_IDLE_IN_TRANSACTION_TIMEOUT_MS=15000
TAKEPLACE_DB_MIGRATION_STATEMENT_TIMEOUT_MS=300000

# --- Reverse proxy trust (PROJECT-SPEC §39.5) --------------------------------
# EXACTLY the Caddy container address on the edge network. No subnet, no "*".
TAKEPLACE_FORWARDED_ALLOW_IPS=${caddy_ip}

# --- CORS / CSRF origin (exact, https only) ----------------------------------
TAKEPLACE_CORS_ORIGINS=https://${domain}

# --- Secrets -----------------------------------------------------------------
TAKEPLACE_IDEMPOTENCY_HMAC_KEY=${idempotency_key}
TAKEPLACE_ABUSE_HMAC_KEY=${abuse_key}
TAKEPLACE_VK_ENCRYPTION_KEYS=1:${vk_key}

# --- Sessions ----------------------------------------------------------------
TAKEPLACE_SESSION_TTL_DAYS=30
TAKEPLACE_SESSION_LAST_SEEN_REFRESH_SECONDS=60
TAKEPLACE_ARGON2_MAX_CONCURRENCY=2
TAKEPLACE_LOGIN_BURST_WINDOW_SECONDS=60
TAKEPLACE_LOGIN_BURST_MAX_REQUESTS=20
TAKEPLACE_LOGIN_RATE_WINDOW_SECONDS=300
TAKEPLACE_LOGIN_RATE_MAX_REQUESTS=10

# --- Realtime ----------------------------------------------------------------
TAKEPLACE_REALTIME_HEARTBEAT_SECONDS=20
TAKEPLACE_REALTIME_QUEUE_MAXSIZE=256
TAKEPLACE_REALTIME_LISTENER_ENABLED=true
TAKEPLACE_REALTIME_SESSION_CHECK_SECONDS=30

# --- VK delivery -------------------------------------------------------------
# No valid VK community credentials exist for this test stand, so delivery is
# off. The independent retention/anonymization maintenance loop still runs (§42.2).
TAKEPLACE_VK_WORKER_ENABLED=false

# --- Privacy / retention / maintenance ---------------------------------------
TAKEPLACE_BOOKING_PII_RETENTION_DAYS=90
TAKEPLACE_OUTBOX_RETENTION_DAYS=30
TAKEPLACE_MAINTENANCE_INTERVAL_SECONDS=3600
TAKEPLACE_MAINTENANCE_BATCH_SIZE=500

# --- Public booking (rate limits only; the venue gate stays closed) ----------
TAKEPLACE_PUBLIC_CAPTCHA_ENABLED=false
TAKEPLACE_PUBLIC_PRIVACY_POLICY_VERSION=1.0.0
TAKEPLACE_REQUEST_IP_HMAC_TTL_DAYS=7
EOF
chmod 600 "$env_path"

echo "wrote $env_path (mode 600, secrets generated, none printed)"
echo "trusted reverse proxy (edge): $caddy_ip"
echo "site origin: https://${domain}"
echo
echo "next: bash deploy/scripts/provision-db.sh && docker compose -f docker-compose.prod.yml up -d --build"
